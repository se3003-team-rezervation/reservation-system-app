import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import os from "node:os";

// Configure isolated store path for test
const testStoreDir = await fs.mkdtemp(path.join(os.tmpdir(), "dormdine-test-"));
process.env.DORM_DINE_STORE_PATH = path.join(testStoreDir, "test-dormdine.json");

const { getDb, saveDb, resetDb } = await import("../lib/store.ts");
const { PATCH } = await import("../app/api/reservations/[id]/route.ts");

test("Manual check-in fallback with 6-character code entry", async (t) => {
  await t.test("matches reservation by exact ID (e.g. RES001)", async () => {
    await resetDb();
    const db = await getDb();
    db.reservations = [
      {
        id: "RES001",
        studentName: "Test Student",
        studentId: "S99999",
        slotId: "l1",
        meal: "lunch",
        startTime: "11:30",
        endTime: "12:00",
        date: "2026-11-20",
        status: "active",
        createdAt: new Date().toISOString(),
      },
    ];
    await saveDb();

    const req = new Request("http://localhost/api/reservations/RES001", {
      method: "PATCH",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ status: "checked-in" }),
    });

    const res = await PATCH(req, { params: Promise.resolve({ id: "RES001" }) });
    assert.equal(res.status, 200);
    const data = await res.json();
    assert.equal(data.id, "RES001");
    assert.equal(data.status, "checked-in");
  });

  await t.test("matches reservation when staff enters 6-character suffix (e.g. 6-char random ID)", async () => {
    await resetDb();
    const db = await getDb();
    // A reservation generated by RES + 6 characters e.g. RESABC123
    db.reservations = [
      {
        id: "RESABC123",
        studentName: "Jane Doe",
        studentId: "S12345",
        slotId: "l2",
        meal: "lunch",
        startTime: "12:00",
        endTime: "12:30",
        date: "2026-11-20",
        status: "active",
        createdAt: new Date().toISOString(),
      },
    ];
    await saveDb();

    // Staff enters just the 6-character code "ABC123"
    const req = new Request("http://localhost/api/reservations/ABC123", {
      method: "PATCH",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ status: "checked-in" }),
    });

    const res = await PATCH(req, { params: Promise.resolve({ id: "ABC123" }) });
    assert.equal(res.status, 200);
    const data = await res.json();
    assert.equal(data.id, "RESABC123");
    assert.equal(data.status, "checked-in");
  });

  await t.test("matches case-insensitively for 6-character code entry", async () => {
    await resetDb();
    const db = await getDb();
    db.reservations = [
      {
        id: "RESXYZ789",
        studentName: "John Smith",
        studentId: "S67890",
        slotId: "d1",
        meal: "dinner",
        startTime: "17:30",
        endTime: "18:00",
        date: "2026-11-20",
        status: "active",
        createdAt: new Date().toISOString(),
      },
    ];
    await saveDb();

    // Staff enters lowercase "xyz789"
    const req = new Request("http://localhost/api/reservations/xyz789", {
      method: "PATCH",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ status: "checked-in" }),
    });

    const res = await PATCH(req, { params: Promise.resolve({ id: "xyz789" }) });
    assert.equal(res.status, 200);
    const data = await res.json();
    assert.equal(data.id, "RESXYZ789");
    assert.equal(data.status, "checked-in");
  });

  await t.test("returns 404 for non-existent 6-character code", async () => {
    const req = new Request("http://localhost/api/reservations/NOEXIST", {
      method: "PATCH",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ status: "checked-in" }),
    });

    const res = await PATCH(req, { params: Promise.resolve({ id: "NOEXIST" }) });
    assert.equal(res.status, 404);
  });

  await t.test("returns 409 when already checked in", async () => {
    const req = new Request("http://localhost/api/reservations/RESXYZ789", {
      method: "PATCH",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ status: "checked-in" }),
    });

    const res = await PATCH(req, { params: Promise.resolve({ id: "RESXYZ789" }) });
    assert.equal(res.status, 409);
    const data = await res.json();
    assert.equal(data.error, "Already checked in");
  });
});
